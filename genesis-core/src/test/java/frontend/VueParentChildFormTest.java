    private ColumnMetadata createColumn(String name, String type, String frontEndType, String uiType, boolean isPrimary, boolean isForeign, boolean isAutoGenerated) {
        ColumnMetadata col = new ColumnMetadata();
        col.setName(name);
        col.setType(type);
        col.setFrontEndType(frontEndType);
        col.setUiType(uiType);
        col.setColumnType(uiType.equals("number") ? "int8" : "varchar");
        col.setPrimary(isPrimary);
        col.setForeign(isForeign);
        col.setAutoGenerated(isAutoGenerated);
        col.setNumeric("number".equals(uiType));
        col.setText("text".equals(uiType));
        col.setNullable(!isPrimary);
        col.setIsParentForeignKey(false);
        col.setReferencedColumn(isForeign ? "id" : "");
        col.setReferencedPrimaryKeyColumn(isForeign ? "id" : "");
        if (isForeign) {
            col.setFrontEndReferencedColumnType("number");
        }
        return col;
    }

    private TableMetadata createTable(String tableName, String className, ColumnMetadata... columns) {
        TableMetadata table = new TableMetadata();
        table.setTableName(tableName);
        table.setClassName(className);
        table.setIsView(false);
        table.setColumns(columns);
        for (ColumnMetadata col : columns) {
            if (col.isPrimary()) {
                table.setPrimaryColumn(col);
                break;
            }
        }
        return table;
    }

    private Component getComponentByType(String type) {
        return vueFramework.getComponents().stream()
                .filter(c -> type.equals(c.getComponentType()))
                .findFirst()
                .orElseThrow(() -> new AssertionError("Component not found for type: " + type));
    }

    private FilesEdit getFilleFileByType(String fileType) {
        return vueFramework.getFilleFiles().stream()
                .filter(f -> fileType.equals(f.getFileType()))
                .findFirst()
                .orElseThrow(() -> new AssertionError("Fille file not found for type: " + fileType));
    }

    @Test
    @DisplayName("RowForm : conserve toutes les FK, utilise getKeyValue() et gère isParentFK dynamiquement")
    void testRowForm_GeneratesAllForeignKeysAndUsesKeyValue() throws Exception {
        // Table Sujet
        ColumnMetadata sujetId = createColumn("id", "Long", "number", "number", true, false, true);
        ColumnMetadata sujetTitre = createColumn("titre", "String", "string", "text", false, false, false);
        TableMetadata sujetTable = createTable("sujets", "Sujet", sujetId, sujetTitre);

        // Table Membre
        ColumnMetadata membreId = createColumn("id", "Long", "number", "number", true, false, true);
        ColumnMetadata membreNom = createColumn("nom", "String", "string", "text", false, false, false);
        TableMetadata membreTable = createTable("membres", "Membre", membreId, membreNom);

        // Table SujetMembre (junction table avec 2 FKs)
        ColumnMetadata smId = createColumn("id", "Long", "number", "number", true, false, true);
        ColumnMetadata smIdSujet = createColumn("idSujet", "Sujet", "Sujet", "number", false, true, false);
        ColumnMetadata smIdMembre = createColumn("idMembre", "Membre", "Membre", "number", false, true, false);
        ColumnMetadata smRole = createColumn("role", "String", "string", "text", false, false, false);
        TableMetadata smTable = createTable("sujets_membres", "SujetMembre", smId, smIdSujet, smIdMembre, smRole);

        // Lier les deux parents à la table enfant (comme dans un vrai scénario)
        sujetTable.addChild(smTable, false, true);
        smTable.addParentTable(sujetTable);

        membreTable.addChild(smTable, false, true);
        smTable.addParentTable(membreTable);

        // Vérifier que côté Java les deux FKs ont isParentForeignKey = true (le bug historique)
        assertTrue(smIdSujet.getIsParentForeignKey(), "smIdSujet doit être marqué parent FK");
        assertTrue(smIdMembre.getIsParentForeignKey(), "smIdMembre doit être marqué parent FK");

        // Rendu du composant Row Form
        FilesEdit rowFormFile = getFilleFileByType("Row Form");

        HashMap<String, Object> metadata = FrameworkFrontendMetadataProvider.getHashMapIntermediaire(smTable, "/destination", "testProject");
        String renderedRowForm = engine.render(rowFormFile.getContent(), metadata);

        // 1. Les deux FKs doivent avoir leur searchField généré (pas éliminées statiquement)
        assertTrue(renderedRowForm.contains("idSujetSearchField"), "idSujetSearchField doit être généré dans le script");
        assertTrue(renderedRowForm.contains("idMembreSearchField"), "idMembreSearchField doit être généré dans le script");

        // 2. Le defaultValue doit utiliser getKeyValue() et NON getReferenceValue()
        assertTrue(renderedRowForm.contains("getKeyValue?.()"), "Doit utiliser getKeyValue() pour le select FK");
        assertFalse(renderedRowForm.contains("?.getReferenceValue?.()"), "Ne doit plus appeler getReferenceValue()");

        // 3. Les props doivent accepter parentClassName et parentFieldName
        assertTrue(renderedRowForm.contains("parentClassName?: string"), "Doit déclarer la prop parentClassName");
        assertTrue(renderedRowForm.contains("parentFieldName?: string"), "Doit déclarer la prop parentFieldName");

        // 4. La fonction isParentFK doit être présente et supporter à la fois fieldName et fkType
        assertTrue(renderedRowForm.contains("const isParentFK"), "Doit déclarer la fonction isParentFK");

        // 5. Les deux cellules <td> doivent exister avec la directive v-if="!isParentFK(...)"
        assertTrue(renderedRowForm.contains("!isParentFK('idSujet', 'Sujet')"), "La cellule idSujet doit utiliser !isParentFK('idSujet', 'Sujet')");
        assertTrue(renderedRowForm.contains("!isParentFK('idMembre', 'Membre')"), "La cellule idMembre doit utiliser !isParentFK('idMembre', 'Membre')");
    }

    @Test
    @DisplayName("TableForm : génère les en-têtes FK dynamiques et passe parentClassName/parentFieldName au RowForm")
    void testTableForm_GeneratesHeadersAndPassesPropsToRowForm() throws Exception {
        ColumnMetadata smId = createColumn("id", "Long", "number", "number", true, false, true);
        ColumnMetadata smIdSujet = createColumn("idSujet", "Sujet", "Sujet", "number", false, true, false);
        ColumnMetadata smIdMembre = createColumn("idMembre", "Membre", "Membre", "number", false, true, false);
        ColumnMetadata smRole = createColumn("role", "String", "string", "text", false, false, false);
        TableMetadata smTable = createTable("sujets_membres", "SujetMembre", smId, smIdSujet, smIdMembre, smRole);

        ColumnMetadata sujetId = createColumn("id", "Long", "number", "number", true, false, true);
        TableMetadata sujetTable = createTable("sujets", "Sujet", sujetId);
        sujetTable.addChild(smTable, false, true);

        FilesEdit tableFormFile = getFilleFileByType("Table Form");

        HashMap<String, Object> metadata = FrameworkFrontendMetadataProvider.getHashMapIntermediaire(smTable, "/destination", "testProject");
        String renderedTableForm = engine.render(tableFormFile.getContent(), metadata);

        // 1. Les en-têtes des deux FKs doivent être générés avec !isParentFK
        assertTrue(renderedTableForm.contains("!isParentFK('idSujet', 'Sujet')"), "L'en-tête idSujet doit utiliser !isParentFK('idSujet', 'Sujet')");
        assertTrue(renderedTableForm.contains("!isParentFK('idMembre', 'Membre')"), "L'en-tête idMembre doit utiliser !isParentFK('idMembre', 'Membre')");

        // 2. Props parentClassName et parentFieldName dans TableForm
        assertTrue(renderedTableForm.contains("parentClassName?: string"), "TableForm doit déclarer la prop parentClassName");
        assertTrue(renderedTableForm.contains("parentFieldName?: string"), "TableForm doit déclarer la prop parentFieldName");

        // 3. Transmission des props au composant RowForm
        assertTrue(renderedTableForm.contains(":parent-class-name=\"parentClassName\""), "Doit transmettre :parent-class-name");
        assertTrue(renderedTableForm.contains(":parent-field-name=\"parentFieldName\""), "Doit transmettre :parent-field-name");
    }

