        // 2. EntityTable reçoit visible-fields et l'événement update (dans le template)
        assertTrue(renderedTemplate.contains(":visible-fields=\"sujetMembreVisibleListFields\""), "EntityTable doit recevoir :visible-fields");
        assertTrue(renderedTemplate.contains("@update:visible-fields=\"handleUpdateSujetMembreVisibleFields\""), "EntityTable doit écouter @update:visible-fields");

        // 3. Script : useSujetMembres, loadColumnConfig et saveColumnConfig (dans l'export)
