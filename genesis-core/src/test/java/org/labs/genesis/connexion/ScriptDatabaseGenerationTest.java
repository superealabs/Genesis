    @Test
    void testGenerateFullProjectComponentsWithNullConnectionDoesNotThrowNPE() throws Exception {
        String sql = """
                CREATE TABLE users (
                    id SERIAL PRIMARY KEY,
                    name VARCHAR(100) NOT NULL
                );
                """;

        ProjectGenerationContext context = new ProjectGenerationContext();
        context.setProjectName("my_test_app");
        context.setDestinationFolder(System.getProperty("java.io.tmpdir") + "/genesis_test_" + System.currentTimeMillis());
        context.setGroupLink("org.example");
        context.setFramework(ProjectGenerator.frameworks.get(Constantes.Spring_REST_API_ID));
        context.setGenerationOptions(new java.util.ArrayList<>());
        context.setFrontendGenerationOptions(new java.util.ArrayList<>());
        context.setFrameworkConfiguration(new java.util.HashMap<>());
        context.setLanguageConfiguration(new java.util.HashMap<>());
        context.setDatabase(postgresDb);
        context.setLanguage(javaLang);
        context.setSqlScript(sql);
        context.setTables();

        // Ensure viewTables is empty
        assertNotNull(context.getViewTables());
        assertTrue(context.getViewTables().isEmpty());

        // Calling generateFullProjectComponents with connex == null must not crash
        ProgressReporter reporter = new NoOpProgressReporter();
        assertDoesNotThrow(() -> {
            List<TableMetadata> entities = projectGenerator.generateFullProjectComponents(context, (java.sql.Connection) null, true, reporter);
            assertNotNull(entities);
            assertEquals(1, entities.size());
        });
    }
