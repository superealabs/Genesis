    @Test
    void testSplitClausesHandlesQuotesAndParentheses() {
        String body = "id INT PRIMARY KEY, " +
                "name VARCHAR(100) NOT NULL, " +
                "price DECIMAL(10,2) DEFAULT 0.0, " +
                "description VARCHAR(200) DEFAULT 'hello, world', " +
                "note TEXT DEFAULT 'it''s, valid'";

        List<String> clauses = SQLRunner.splitClauses(body);
        assertEquals(5, clauses.size());
        assertEquals("id INT PRIMARY KEY", clauses.get(0));
        assertEquals("name VARCHAR(100) NOT NULL", clauses.get(1));
        assertEquals("price DECIMAL(10,2) DEFAULT 0.0", clauses.get(2));
        assertEquals("description VARCHAR(200) DEFAULT 'hello, world'", clauses.get(3));
        assertEquals("note TEXT DEFAULT 'it''s, valid'", clauses.get(4));
    }

    @Test
    void testFetchColumnsFromPostgresScript() {
        String body = """
                id SERIAL PRIMARY KEY,
                title VARCHAR(255) NOT NULL,
                amount DOUBLE PRECISION,
                created_at TIMESTAMP WITH TIME ZONE,
                author_id INT REFERENCES authors(id)
                """;

        List<ColumnMetadata> cols = postgresDb.fetchColumnsFromScript(body, javaLang);
        assertEquals(5, cols.size());

        // id SERIAL PRIMARY KEY
        ColumnMetadata idCol = cols.get(0);
        assertEquals("id", idCol.getReferencedColumn());
        assertEquals("id", idCol.getName());
        assertTrue(idCol.isPrimary());
        assertTrue(idCol.isAutoGenerated(), "SERIAL must be autoGenerated");
        assertFalse(idCol.isNullable(), "Primary key must not be nullable");
        assertTrue(idCol.isNumeric());
        assertEquals("Integer", idCol.getType());

        // title VARCHAR(255) NOT NULL
        ColumnMetadata titleCol = cols.get(1);
        assertEquals("title", titleCol.getReferencedColumn());
        assertFalse(titleCol.isPrimary());
        assertFalse(titleCol.isNullable());
        assertTrue(titleCol.isText());
        assertEquals("String", titleCol.getType());

        // amount DOUBLE PRECISION
        ColumnMetadata amountCol = cols.get(2);
        assertTrue(amountCol.isNumeric());
        assertTrue(amountCol.isNumericWithPrecision());
        assertEquals("Double", amountCol.getType());

        // created_at TIMESTAMP WITH TIME ZONE
        ColumnMetadata dateCol = cols.get(3);
        assertTrue(dateCol.isDateTime());
        assertTrue(dateCol.isDateTimeTz());

        // author_id INT REFERENCES authors(id)
        ColumnMetadata fkCol = cols.get(4);
        assertTrue(fkCol.isForeign());
        assertEquals("authors", fkCol.getReferencedTable());
        assertEquals("id", fkCol.getReferencedPrimaryKeyColumn());
    }

